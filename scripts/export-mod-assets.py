#!/usr/bin/env python3
"""Write the ClaudeGlass mod's generated assets into
``plugin/hooks/generated/``.

The mod runs inside Claude Code. It can't import Python and its engine
loads only script files, never JSON, so what it shares with ClaudeGlass is
written here as ES modules, one per topic:

- ``copy.js``: the mod's own words and the pane's glossary
  (``claudeglass.mod_copy``), kept in Python so the house-style tests
  cover them;
- ``coaching.js``: the coaching thresholds, tips and how-to words
  (``claudeglass.capture_catalogue``), so the mod says what the capture
  hook says, with the hints it delivers itself and the words its sensor
  file may carry;
- ``palette.js``: the dashboard's chart, status and surface colours in the
  light and dark themes (``service/static/app.css``) and its colours per
  entity (``service/static/charts.js`` ``ENTITY_COLOURS``);
- ``rates.js``: the packaged ``pricing.toml`` as the mod's fallback prices,
  in the shape of the ``pricing`` block of the mod's settings file
  (``claudeglass.mod_settings``);
- ``version.js``: ``claudeglass.__version__``.

Usage::

    python scripts/export-mod-assets.py [--check]

``--check`` writes nothing: it exits 1, naming each file that is not what
:func:`export` produces now. ``tests/test_mod_assets.py`` does the same, so
a change to any source above fails until this script is run again.

The output is deterministic: no timestamps, sorted keys, ``\\n`` line
ends. :func:`export` returns it as ``{relative path: text}`` without
writing anything.

Why the entity colours are parsed from ``charts.js`` rather than mirrored
in Python: the dashboard's map is the one source, so a colour changed there
reaches the mod on the next run and no second copy can drift. The parse
reads only the object literal's string keys and ``var(--token)`` values.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = REPO_ROOT / "src"
PACKAGE_DIR = SRC_DIR / "claudeglass"
STATIC_DIR = PACKAGE_DIR / "service" / "static"
OUTPUT_DIR = REPO_ROOT / "plugin" / "hooks" / "generated"

if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from claudeglass import __version__, capture_catalogue, mod_copy, mod_settings  # noqa: E402
from claudeglass.pricing import load_pricing  # noqa: E402

#: The custom properties a chart, a status or a surface in the mod needs.
#: A token belongs when its name starts with one of these.
PALETTE_PREFIXES = (
    "surface-",
    "border",
    "ink-",
    "accent",
    "on-accent",
    "focus",
    "good",
    "warn",
    "serious",
    "critical",
    "chart-",
    "seq-",
    "div-",
    "grid-line",
    "axis-line",
)

_TOKEN_RE = re.compile(r"--([a-z0-9-]+)\s*:\s*([^;]+);")
_VAR_RE = re.compile(r"var\(--([a-z0-9-]+)\)")
#: A literal colour, as app.css writes one.
_COLOUR_RE = re.compile(r"#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)")


def _header(*sources: str) -> str:
    return f"// Generated by scripts/export-mod-assets.py from {', '.join(sources)}. Do not edit.\n"


def _module(sources: tuple[str, ...], exports: dict[str, object]) -> str:
    """An ES module: the header, then ``export const NAME = <JSON>;`` for
    each export, in the order given."""
    parts = [_header(*sources)]
    for name, value in exports.items():
        parts.append(f"\nexport const {name} = {json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False)};\n")
    return "".join(parts)


# -- the dashboard's colours ---------------------------------------------------


def _block(css: str, opener: str) -> str:
    """The text between the braces of each block that opens with ``opener``
    at the start of a line, joined."""
    bodies = []
    for match in re.finditer(r"^" + re.escape(opener) + r"\s*\{", css, flags=re.MULTILINE):
        depth, end = 1, match.end()
        while depth and end < len(css):
            depth += {"{": 1, "}": -1}.get(css[end], 0)
            end += 1
        bodies.append(css[match.end() : end - 1])
    return "\n".join(bodies)


def _tokens(block: str) -> dict[str, str]:
    return {name: value.strip() for name, value in _TOKEN_RE.findall(block)}


def _resolve(value: str, tokens: dict[str, str], depth: int = 0) -> str:
    """``value`` with each ``var(--x)`` replaced by that token's value."""
    if depth > 8:
        raise ValueError(f"colour tokens refer to each other without end: {value!r}")
    return _VAR_RE.sub(lambda match: _resolve(tokens[match.group(1)], tokens, depth + 1), value)


def themes() -> dict[str, dict[str, str]]:
    """The palette's tokens in each theme, as literal colours: the light
    ``:root`` block, and the dark block laid over it (a token the dark
    block does not repeat keeps its light value)."""
    css = (STATIC_DIR / "app.css").read_text(encoding="utf-8")
    light = _tokens(_block(css, ":root"))
    dark = {**light, **_tokens(_block(css, ':root[data-theme="dark"]'))}
    out = {}
    for theme, tokens in (("light", light), ("dark", dark)):
        out[theme] = {
            name: resolved
            for name, value in tokens.items()
            if name.startswith(PALETTE_PREFIXES)
            for resolved in [_resolve(value, tokens)]
            if _COLOUR_RE.fullmatch(resolved)
        }
    return out


def entity_colours() -> dict[str, dict[str, dict[str, str]]]:
    """``charts.js`` ``ENTITY_COLOURS`` as ``{kind: {key: {light, dark}}}``,
    each ``var(--x)`` resolved in both themes."""
    source = (STATIC_DIR / "charts.js").read_text(encoding="utf-8")
    start = source.index("export var ENTITY_COLOURS = {") + len("export var ENTITY_COLOURS = ")
    depth, end = 0, start
    while True:
        depth += {"{": 1, "}": -1}.get(source[end], 0)
        end += 1
        if depth == 0:
            break
    literal = re.sub(r"^\s*//.*$", "", source[start:end], flags=re.MULTILINE)
    literal = re.sub(r'"(?:[^"\\]|\\.)*"|([A-Za-z_]\w*)\s*:', lambda m: m.group(0) if m.group(1) is None else f'"{m.group(1)}":', literal)
    kinds = json.loads(re.sub(r",(\s*[}\]])", r"\1", literal))
    palette = themes()
    out: dict[str, dict[str, dict[str, str]]] = {}
    for kind, keys in kinds.items():
        out[kind] = {}
        for key, value in keys.items():
            match = _VAR_RE.fullmatch(value)
            if match is None:
                raise ValueError(f"ENTITY_COLOURS.{kind}.{key} is not a var(--token): {value!r}")
            out[kind][key] = {theme: palette[theme][match.group(1)] for theme in ("light", "dark")}
    return out


# -- the capture hook's patterns, for the coaching the mod runs ------------------

#: The inline flags Python allows at the start of a pattern, as JavaScript's.
_INLINE_FLAGS = {"i": "i", "m": "m", "s": "s"}
_UNICODE_ESCAPE = re.compile(r"\\U([0-9a-fA-F]{8})")


def _js_escape(match: re.Match) -> str:
    r"""``\UXXXXXXXX`` as JavaScript writes the same character without the
    ``u`` flag: ``\uXXXX``, or a surrogate pair for one past 0xFFFF."""
    code = int(match.group(1), 16)
    if code <= 0xFFFF:
        return "\\u%04X" % code
    code -= 0x10000
    return "\\u%04X\\u%04X" % (0xD800 + (code >> 10), 0xDC00 + (code & 0x3FF))


def js_pattern(pattern: str) -> dict[str, str]:
    r"""A catalogue pattern as ``{source, flags}`` for ``new RegExp``: the
    inline flags it opens with moved to the flags, ``\U`` escapes and
    ``\Z`` rewritten. Nothing else differs between the two dialects for
    the patterns the mod reads (a test compiles each and holds it to the
    Python on a spread of text)."""
    flags = ""
    while True:
        found = re.match(r"\(\?([ims]+)\)", pattern)
        if found is None:
            break
        flags += "".join(_INLINE_FLAGS[letter] for letter in found.group(1) if _INLINE_FLAGS[letter] not in flags)
        pattern = pattern[found.end():]
    pattern = _UNICODE_ESCAPE.sub(_js_escape, pattern).replace("\\Z", "(?![\\s\\S])")
    return {"source": pattern, "flags": flags}


def coach_patterns() -> dict[str, object]:
    """What ``plugin/hooks/lib/coach.js`` reads to decide the hints the
    capture hook decides by text: a status check, a change request, a reply
    that asks, a tool call that changes a file, a background launch.
    Pattern names are the catalogue's, lower-cased, less ``_PATTERN``."""
    c = capture_catalogue
    names = (
        "STATUS", "GO", "ASKS", "REVIEW", "ACK", "CHANGE", "CONFIG_PATH", "SHELL_WRITE", "BACKGROUND_LAUNCH",
        "TASK_NOTIFICATION_CALL", "REPLY_FENCE", "REPLY_TIP_BLOCK", "REPLY_INLINE_CODE", "REPLY_URL",
        "REPLY_QUOTED", "REPLY_REMINDER_LINE", "REPLY_TAGS", "REPLY_LIST_START", "REPLY_UNIT",
    )
    out: dict[str, object] = {name.lower(): js_pattern(getattr(c, f"{name}_PATTERN")) for name in names}
    out.update(
        {
            "status_max_chars": c.STATUS_MAX_CHARS,
            "go_max_chars": c.GO_MAX_CHARS,
            "change_scan_chars": c.CHANGE_SCAN_CHARS,
            "background_scan_chars": c.BACKGROUND_SCAN_CHARS,
            "reply_scan_chars": c.REPLY_SCAN_CHARS,
            "reply_question_trim": c.REPLY_QUESTION_TRIM,
            "task_notification_prefix": c.TASK_NOTIFICATION_PREFIX,
            "edit_tools": list(c.EDIT_TOOLS),
            "feedback_skill": c.FEEDBACK_SKILL,
        }
    )
    return out


# -- the files ------------------------------------------------------------------


def export() -> dict[str, str]:
    """Every generated file, as ``{path relative to the repository: text}``.
    Nothing is written."""
    # The packaged rate card by its path, not the one in the reader's own
    # config folder, so the output is the same on every machine.
    pricing = mod_settings.pricing_block(load_pricing(path=PACKAGE_DIR / "pricing.toml"))
    files = {
        "copy.js": _module(("src/claudeglass/mod_copy.py",), {"COPY": mod_copy.COPY, "GLOSSARY": mod_copy.GLOSSARY}),
        # COACHING_THRESHOLDS, COACHING_TIP and COACHING_HOW are plain dicts of
        # numbers and strings, so they convert as they are.
        "coaching.js": _module(
            ("src/claudeglass/capture_catalogue.py",),
            {
                "THRESHOLDS": capture_catalogue.COACHING_THRESHOLDS,
                "TIPS": capture_catalogue.COACHING_TIP,
                "HOW": capture_catalogue.COACHING_HOW,
                # What ``split_run`` says an agent run did, and the agent
                # types the coaching never covers (the agents feature).
                "SPLIT_WHY": capture_catalogue.COACHING_SPLIT_WHY,
                "SKIP_AGENT_TYPES": list(capture_catalogue.SKIP_AGENT_TYPES),
                # The patterns the hints decided by text read (``coach.js``).
                "PATTERNS": coach_patterns(),
                # The hints the mod delivers itself, which the capture hook
                # leaves out while the mod runs (``MOVED_TO_MOD``), and the
                # words its sensor file may carry (``SENSOR_VOCAB``), as
                # sorted lists so the output is the same on every run.
                "MOVED": sorted(capture_catalogue.MOVED_TO_MOD),
                "NOTE_KINDS": list(capture_catalogue.SENSOR_NOTE_KINDS),
                "MOD_NOTE_KINDS": list(capture_catalogue.MOD_NOTE_KINDS),
                "SENSOR_EVENTS": list(capture_catalogue.SENSOR_EVENTS),
                "SENSOR_VOCAB": capture_catalogue.SENSOR_VOCAB,
            },
        ),
        "palette.js": _module(
            ("src/claudeglass/service/static/app.css", "src/claudeglass/service/static/charts.js"),
            {"PALETTE": themes(), "ENTITIES": entity_colours()},
        ),
        "rates.js": _module(
            ("src/claudeglass/pricing.toml", "src/claudeglass/mod_settings.py"), {"RATES": pricing}
        ),
        "version.js": _module(("src/claudeglass/__init__.py",), {"VERSION": __version__}),
    }
    return {f"plugin/hooks/generated/{name}": text for name, text in files.items()}


def write(files: dict[str, str] | None = None) -> list[Path]:
    """Write :func:`export`'s files (or ``files``) under the repository and
    return their paths."""
    paths = []
    for relative, text in (files if files is not None else export()).items():
        path = REPO_ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        paths.append(path)
    return paths


def stale(files: dict[str, str] | None = None) -> list[str]:
    """The relative paths whose file on disk is not :func:`export`'s text."""
    out = []
    for relative, text in (files if files is not None else export()).items():
        path = REPO_ROOT / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            out.append(relative)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing: exit 1, naming each generated file that is out of date",
    )
    args = parser.parse_args(argv)
    files = export()
    if args.check:
        behind = stale(files)
        for relative in behind:
            print(f"OUT OF DATE: {relative}", file=sys.stderr)
        if not behind:
            print(f"{len(files)} generated files are up to date")
        return 1 if behind else 0
    for path in write(files):
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
