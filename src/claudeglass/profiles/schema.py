"""Profile schema (V3-profiles): the on-disk/in-memory shape of a
claudeglass profile (plan Appendix A7 and the "Milestone v0.3 --
baseline capture, archetype, profiles, apply" section) and the allowlist
that is the *single source of truth* for what a profile may contain.

A profile only ever names a documented Claude Code lever -- never a
value the harness has no way to honour -- so the schema itself is the
enforcement point the plan asks for ("the schema rejects anything else
so a profile can never promise an effect the harness cannot deliver",
quoted again in ``docs/api.md``'s ``POST /api/profiles`` note). Every
allowlisted key carries its permitted type/values, which *kind* of lever
it is (a top-level settings key, a per-agent frontmatter path, or an
environment variable name), and a documentation reference, so a
validation failure and a rendered doc table both come from the exact
same data (see ``docs/profiles.md``, generated by hand from these three
dicts to keep them from drifting apart).

This module is deliberately the only place in this package that
constructs or serialises a :class:`Profile` -- ``catalogue.py`` and
``diff.py`` both import it rather than duplicating any of this.

Deviations from the plan/brief, reported rather than made silently (see
``model.py``'s module docstring for this project's convention on this):

- **``notes`` is placed before the ``[settings]``/``[agents.*]``/``[env]``
  tables in :func:`dump_profile`'s output, not after ``[env]`` the way
  Appendix A7's illustrative snippet writes it.** Appendix A7 places
  ``notes = "..."`` as the very last line, directly below an
  ``[env]`` table with no further table header — but TOML has no
  "closed" table: every bare ``key = value`` line belongs to the most
  recently opened table header, so a real TOML parser (``tomllib``, and
  every other implementation) would fold that ``notes`` value into
  ``[env]`` itself rather than reading it as a top-level field. Since
  ``Profile.notes`` is a genuine top-level field (per this work
  package's own dataclass spec), :func:`dump_profile` writes it as a
  bare top-level key ahead of any table header, which is both valid
  TOML and round-trips correctly. A7's ordering is kept for the
  ``id``/``name``/``for``/``archetype``/``[settings]``/``[agents.*]``/
  ``[env]`` sections exactly as shown.
- **``recommend.py``'s baseline-bloat rule carries no lever.** It used
  to emit a bare ``"mcpServers"``, which is no settings key (MCP servers
  live in ``~/.claude.json`` and ``.mcp.json``), so ``--patch-set``
  printed a settings change that doesn't exist, and
  :data:`RECOMMEND_LEVER_MAP` mapped it to ``disabledMcpjsonServers``.
  Its fix is a prompt now, and the mapping is gone. Every lever
  ``recommend.py``/``ttl.py`` still emits resolves to an allowlisted key;
  see ``tests/test_profiles_schema.py`` for the regression test.
"""

