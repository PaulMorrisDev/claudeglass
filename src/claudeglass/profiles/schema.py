class ProfileError(ValueError):
    """A profile document failed :func:`validate`. ``problems`` carries
    the full list of messages ``validate`` produced (never just the
    first one), so a caller printing this exception's ``str()`` sees
    every problem at once, matching :func:`validate`'s own contract."""

    def __init__(self, problems: list[str]) -> None:
        self.problems = list(problems)
        super().__init__("; ".join(self.problems) if self.problems else "invalid profile")


@dataclass(frozen=True, slots=True)
class LeverSpec:
    """One allowlisted key's shape: its permitted Python type, which kind
    of lever it is (see the three ``scope_kind`` values below), the
    values an ``"enum"`` kind accepts, the inclusive range an ``"int"``
    kind accepts, and a documentation anchor for :func:`validate`'s
    error text / ``docs/profiles.md``'s table.

    ``scope_kind`` is one of:

    - ``"settings"`` -- a top-level Claude Code ``settings.json`` key.
    - ``"agent frontmatter"`` -- a ``.claude/agents/<name>.md`` frontmatter
      field (only meaningful nested under ``Profile.agents["<name>"]``).
    - ``"env"`` -- an environment variable *name* (the allowlist governs
      which names a profile may mention; the value is always a free-form
      string the user supplies at apply time, per the plan's "names
      only here; values supplied at apply time" A7 comment).
    """

    kind: str  # "str" | "enum" | "int" | "bool" | "list[str]" | "map[str,bool]" | "map[str,enum]"
    scope_kind: str  # "settings" | "agent frontmatter" | "env"
    values: tuple[str, ...] | None = None
    min: int | None = None
    max: int | None = None
    doc_ref: str = ""


