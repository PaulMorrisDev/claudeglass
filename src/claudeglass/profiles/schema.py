# -- Profile dataclass -------------------------------------------------


@dataclass(frozen=True, slots=True)
class Profile:
    """One profile document -- either a shipped catalogue entry
    (``profiles/catalogue/<id>.toml``) or a user/API-submitted one. See
    plan Appendix A7 for the on-disk shape this mirrors field-for-field
    (``for`` renamed ``for_`` here since it is a Python keyword)."""

    id: str = ""
    name: str = ""
    for_: tuple[str, ...] = ()
    archetype: str | None = None
    settings: dict = field(default_factory=dict)
    #: agent name -> {allowlisted key: value}, keys already normalised to
    #: the dotted ``"experimental.cacheTtl"`` form.
    agents: dict = field(default_factory=dict)
    env: dict = field(default_factory=dict)
    notes: str = ""
    #: Where this profile was loaded from, if it was loaded from a file
    #: (``load_profile``) rather than a dict/string. Never written by
    #: ``dump_profile`` and never part of equality (a round trip through
    #: dump/load must compare equal regardless of where either copy came
    #: from) -- see the module docstring's "never exported" note.
    source_path: str | None = field(default=None, compare=False, repr=False)


# -- validation ----------------------------------------------------------


def _type_ok(value, spec: LeverSpec) -> bool:
    if spec.kind == "str":
        return isinstance(value, str)
    if spec.kind == "enum":
        return isinstance(value, str) and spec.values is not None and value in spec.values
    if spec.kind == "int":
        if not isinstance(value, int) or isinstance(value, bool):
            return False
        if spec.min is not None and value < spec.min:
            return False
        if spec.max is not None and value > spec.max:
            return False
        return True
    if spec.kind == "bool":
        return isinstance(value, bool)
    if spec.kind == "list[str]":
        return isinstance(value, list) and all(isinstance(item, str) for item in value)
    if spec.kind == "map[str,bool]":
        return isinstance(value, dict) and all(
            isinstance(k, str) and isinstance(v, bool) for k, v in value.items()
        )
    if spec.kind == "map[str,enum]":
        return isinstance(value, dict) and all(
            isinstance(k, str) and isinstance(v, str) and v in (spec.values or ()) for k, v in value.items()
        )
    return False  # pragma: no cover - every LeverSpec.kind above is exhaustive


def _describe_expected(spec: LeverSpec) -> str:
    if spec.kind == "enum":
        return f"one of {', '.join(spec.values or ())}"
    if spec.kind == "int":
        bounds = ""
        if spec.min is not None or spec.max is not None:
            bounds = f" between {spec.min if spec.min is not None else '-inf'} and {spec.max if spec.max is not None else 'inf'}"
        return f"an int{bounds}"
    if spec.kind == "bool":
        return "a bool"
    if spec.kind == "list[str]":
        return "a list of strings"
    if spec.kind == "map[str,bool]":
        return "a table of names to true or false"
    if spec.kind == "map[str,enum]":
        return f"a table of names to one of {', '.join(spec.values or ())}"
    return "a string"


def _normalise_agent_dict(agent_name: str, raw: dict, problems: list[str]) -> dict:
    """Returns ``raw`` with a nested ``experimental = {cacheTtl = ...}``
    table folded into the dotted ``"experimental.cacheTtl"`` key (plan:
    "accept both the dotted key and a nested ``experimental = { cacheTtl
    = ... }`` table, normalise to dotted"). Appends a problem and leaves
    the dotted key unset if both forms are given with different values,
    or if the nested table holds anything other than ``cacheTtl``."""
    out = dict(raw)
    nested = out.pop("experimental", None)
    if nested is None:
        return out
    if not isinstance(nested, dict):
        problems.append(f"agents.{agent_name}.experimental: must be a table, got {type(nested).__name__}")
        return out
    extra_keys = set(nested) - {"cacheTtl"}
    if extra_keys:
        problems.append(
            f"agents.{agent_name}.experimental: unknown key(s) {sorted(extra_keys)} "
            "(only 'cacheTtl' is allowlisted under a nested experimental table)"
        )
    if "cacheTtl" not in nested:
        return out
    dotted_value = out.get("experimental.cacheTtl")
    nested_value = nested["cacheTtl"]
    if "experimental.cacheTtl" in out and dotted_value != nested_value:
        problems.append(
            f"agents.{agent_name}: both 'experimental.cacheTtl' ({dotted_value!r}) and a nested "
            f"experimental.cacheTtl ({nested_value!r}) were given with different values"
        )
    else:
        out["experimental.cacheTtl"] = nested_value
    return out


def validate(d: dict) -> list[str]:
    """Every problem with profile document ``d`` (already-parsed TOML or
    JSON, i.e. a plain ``dict``): unknown top-level/settings/agent/env
    keys, wrong types, out-of-range values, an unknown ``archetype``, and
    an ``id`` that does not match ``^[a-z0-9-]{1,40}$``. An empty list
    means ``d`` is a valid profile. Never raises on a malformed shape --
    every check degrades to a problem message instead (matching this
    project's "never crash on a foreign shape" convention -- see
    ``config.py``/``snapshots.py``'s module docstrings)."""
    problems: list[str] = []

    if not isinstance(d, dict):
        return [f"profile: must be a table/object, got {type(d).__name__}"]

    unknown_top = sorted(set(d) - _TOP_LEVEL_KEYS)
    for key in unknown_top:
        problems.append(f"{key}: unknown top-level key")

    profile_id = d.get("id")
    if not isinstance(profile_id, str) or not profile_id:
        problems.append("id: required, must be a non-empty string")
    elif not _ID_RE.match(profile_id):
        problems.append(f"id: must match ^[a-z0-9-]{{1,40}}$, got {profile_id!r}")

    if "name" in d and not isinstance(d["name"], str):
        problems.append(f"name: must be a string, got {type(d['name']).__name__}")

    if "for" in d:
        for_value = d["for"]
        if not isinstance(for_value, list) or not all(isinstance(item, str) for item in for_value):
            problems.append("for: must be a list of strings")

    if "archetype" in d and d["archetype"] is not None:
        archetype = d["archetype"]
        if not isinstance(archetype, str) or archetype not in ARCHETYPES:
            problems.append(f"archetype: unknown archetype {archetype!r} (expected one of {', '.join(ARCHETYPES)})")

    if "notes" in d and not isinstance(d["notes"], str):
        problems.append(f"notes: must be a string, got {type(d['notes']).__name__}")

    settings = d.get("settings", {})
    if not isinstance(settings, dict):
        problems.append(f"settings: must be a table/object, got {type(settings).__name__}")
    else:
        for key, value in settings.items():
            spec = SETTINGS_ALLOWLIST.get(key)
            if spec is None:
                problems.append(f"settings.{key}: unknown key")
                continue
            if not _type_ok(value, spec):
                problems.append(f"settings.{key}: must be {_describe_expected(spec)}, got {value!r}")

    agents = d.get("agents", {})
    if not isinstance(agents, dict):
        problems.append(f"agents: must be a table/object, got {type(agents).__name__}")
    else:
        for agent_name, agent_dict in agents.items():
            if not isinstance(agent_dict, dict):
                problems.append(f"agents.{agent_name}: must be a table/object, got {type(agent_dict).__name__}")
                continue
            normalised = _normalise_agent_dict(agent_name, agent_dict, problems)
            for key, value in normalised.items():
                spec = AGENT_ALLOWLIST.get(key)
                if spec is None:
                    problems.append(f"agents.{agent_name}.{key}: unknown key")
                    continue
                if not _type_ok(value, spec):
                    problems.append(f"agents.{agent_name}.{key}: must be {_describe_expected(spec)}, got {value!r}")

    env = d.get("env", {})
    if not isinstance(env, dict):
        problems.append(f"env: must be a table/object, got {type(env).__name__}")
    else:
        for name, value in env.items():
            if name not in ENV_ALLOWLIST:
                problems.append(f"env.{name}: not an allowed environment variable name")
            elif not isinstance(value, str):
                problems.append(f"env.{name}: value must be a string, got {type(value).__name__}")

    return problems


# -- loading ---------------------------------------------------------------


def load_dict(d: dict, *, source_path: str | None = None) -> Profile:
    """Validates ``d`` (raises :class:`ProfileError` on any problem) and
    builds the :class:`Profile` it describes. This is the one function
    every loader (:func:`load_profile`, :func:`loads_profile`) and the
    service's ``POST /api/profiles`` route (which hands this function a
    JSON body already parsed into a plain dict -- see ``docs/api.md``)
    funnel through."""
    problems = validate(d)
    if problems:
        raise ProfileError(problems)

    agents_raw = d.get("agents", {}) or {}
    agents: dict = {}
    for agent_name, agent_dict in agents_raw.items():
        normalised_problems: list[str] = []
        agents[agent_name] = _normalise_agent_dict(agent_name, agent_dict, normalised_problems)
        # validate() above already proved this normalisation raises no
        # new problems for a document that passed validation -- assert
        # rather than silently trust, so a future validate()/load_dict()
        # drift is caught immediately instead of shipping a bad Profile.
        assert not normalised_problems, normalised_problems

    return Profile(
        id=d["id"],
        name=d.get("name", ""),
        for_=tuple(d.get("for", ()) or ()),
        archetype=d.get("archetype"),
        settings=dict(d.get("settings", {}) or {}),
        agents=agents,
        env=dict(d.get("env", {}) or {}),
        notes=d.get("notes", ""),
        source_path=source_path,
    )


def loads_profile(text: str) -> Profile:
    """Parses ``text`` as a TOML profile document and returns the
    :class:`Profile` it describes (see :func:`load_dict`)."""
    data = tomllib.loads(text)
    return load_dict(data)


def load_profile(path: str | Path) -> Profile:
    """Reads and parses the TOML profile document at ``path``. The
    returned :class:`Profile`'s ``source_path`` is ``str(path)``."""
    path = Path(path)
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    return load_dict(data, source_path=str(path))


# -- dumping (minimal deterministic TOML emitter) ---------------------------
#
# ``tomllib`` (stdlib) is read-only -- there is no stdlib TOML writer, so
# this hand-rolls the narrow subset of TOML the schema above actually
# needs: bare top-level scalars/lists, and simple non-nested tables
# (``[settings]``, ``[agents.<name>]``, ``[env]``) of scalars/lists. Every
# section's keys are emitted in the allowlist's own fixed iteration order
# (not the ``dict``'s insertion order) so two calls with the same profile
# content always produce byte-identical output regardless of how the
# caller built the dict -- the "byte-stable ordering" this package's
# other deliverable (``diff.py``'s ``render_unified_diff``) also commits
# to, for the same reason: a diff/dump that reorders itself between runs
# is useless for a git-style comparison.


def _toml_escape(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return "".join(out)


def _toml_string(s: str) -> str:
    return f'"{_toml_escape(s)}"'


def _toml_key(k: str) -> str:
    return k if _BARE_TOML_KEY_RE.match(k) else _toml_string(k)


def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return _toml_string(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_toml_value(item) for item in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{_toml_string(k)} = {_toml_value(item)}" for k, item in v.items()) + " }"
    raise TypeError(f"cannot emit {v!r} as TOML")  # pragma: no cover - schema-validated inputs only


def dump_profile(profile: Profile) -> str:
    """Deterministic TOML text for ``profile`` -- ``source_path`` is
    never emitted (see the module/``Profile`` docstrings' "never
    exported" note). ``load_profile(io) -> dump_profile -> loads_profile``
    round-trips to an equal :class:`Profile` (excluding ``source_path``,
    which is excluded from equality too) for every value the allowlist
    permits."""
    lines: list[str] = []
    lines.append(f"id = {_toml_string(profile.id)}")
    if profile.name:
        lines.append(f"name = {_toml_string(profile.name)}")
    if profile.for_:
        lines.append(f"for = {_toml_value(list(profile.for_))}")
    if profile.archetype:
        lines.append(f"archetype = {_toml_string(profile.archetype)}")
    if profile.notes:
        lines.append(f"notes = {_toml_string(profile.notes)}")

    if profile.settings:
        lines.append("")
        lines.append("[settings]")
        for key in SETTINGS_ALLOWLIST:
            if key in profile.settings:
                lines.append(f"{_toml_key(key)} = {_toml_value(profile.settings[key])}")

    for agent_name in sorted(profile.agents):
        agent_dict = profile.agents[agent_name]
        if not agent_dict:
            continue
        lines.append("")
        lines.append(f"[agents.{_toml_key(agent_name)}]")
        for key in AGENT_ALLOWLIST:
            if key in agent_dict:
                lines.append(f"{_toml_key(key)} = {_toml_value(agent_dict[key])}")

    if profile.env:
        lines.append("")
        lines.append("[env]")
        for name in ENV_ALLOWLIST:
            if name in profile.env:
                lines.append(f"{_toml_key(name)} = {_toml_value(profile.env[name])}")

    return "\n".join(lines).rstrip("\n") + "\n"


# -- recommend.py lever coverage --------------------------------------------

#: A per-agent-type TTL lever's text, e.g. ``"experimental.cacheTtl in
#: claude-implementer.md (or subagentPromptCacheTtl for all subagents)"``
#: (``ttl.TtlTypeStats.lever``) -- duplicated from
#: ``recommend._AGENT_LEVER_RE`` rather than imported, since this module
#: must not depend on ``recommend.py`` (the dependency runs the other way:
#: a later work package's ``apply``/service routes import *this* module
#: to act on a ``Recommendation.lever`` string).
_AGENT_LEVER_RE = re.compile(r"experimental\.cacheTtl in ([^.]+)\.md")

#: Maps a bare lever string ``recommend.py`` can emit directly (a literal
#: ``lever="..."``/``lever = "..."`` in a ``Recommendation(...)`` call)
#: onto the ``(scope_kind, allowlisted key)`` pair it represents.
RECOMMEND_LEVER_MAP: dict[str, tuple[str, str]] = {
    "promptCacheTtl": ("settings", "promptCacheTtl"),
    "autoCompactWindow": ("settings", "autoCompactWindow"),
    "effortLevel": ("settings", "effortLevel"),
    "omitClaudeMd": ("agent frontmatter", "omitClaudeMd"),
    # COV-09: the deprecated-setting rule's bare settings-key lever.
    "includeCoAuthoredBy": ("settings", "includeCoAuthoredBy"),
}

#: COV-09: recommend.py's five env-var lever rules emit ``f"env:{NAME}"``
#: (one rule's own name is chosen dynamically -- whichever
#: ``DISABLE_PROMPT_CACHING*`` variant a snapshot actually has set, or the
#: bare ``DISABLE_PROMPT_CACHING`` name when more than one is), so this is
#: a *prefix* convention rather than a fixed set of literals
#: :data:`RECOMMEND_LEVER_MAP` could enumerate -- unlike the agent-lever
#: sentence form above, the part after the prefix is already the exact
#: :data:`ENV_ALLOWLIST` key, no further parsing needed.
_ENV_LEVER_PREFIX = "env:"


def recommend_lever_key(lever: str) -> tuple[str, str] | None:
    """The ``(scope_kind, allowlisted key)`` pair the raw ``lever`` string
    a ``Recommendation`` carries represents, or ``None`` if ``lever``
    names nothing a profile can encode (``lever=None`` recommendations --
    out of scope for a profile by design; workflow advice, not a
    setting). Handles the bare literals in :data:`RECOMMEND_LEVER_MAP`,
    ``ttl.TtlTypeStats.lever``'s per-agent-type sentence form via
    :data:`_AGENT_LEVER_RE` (exactly the same pattern
    ``recommend._lever_scope``/``recommend.render_patch_set`` already use
    to recognise it), and an ``"env:NAME"``-prefixed lever (COV-09) by
    stripping the prefix and checking :data:`ENV_ALLOWLIST` directly --
    ``None`` if ``NAME`` isn't allowlisted, so an unlisted env lever fails
    the same way an unlisted settings/agent key would."""
    if lever in RECOMMEND_LEVER_MAP:
        return RECOMMEND_LEVER_MAP[lever]
    if _AGENT_LEVER_RE.search(lever):
        return ("agent frontmatter", "experimental.cacheTtl")
    if lever.startswith(_ENV_LEVER_PREFIX):
        name = lever[len(_ENV_LEVER_PREFIX):]
        if name in ENV_ALLOWLIST:
            return ("env", name)
        return None
    return None


# -- sanity: keep the dataclass field list and TOP_LEVEL_KEYS in sync -------
#
# A future contributor adding a new Profile field without also adding it
# to _TOP_LEVEL_KEYS (or vice versa) would silently make validate() and
# load_dict() disagree about what a profile may contain. Assert it once
# at import time rather than relying on a test to catch it.
_PROFILE_FIELD_NAMES = {f.name for f in fields(Profile)} - {"source_path"}
_EXPECTED_TOP_LEVEL = {("for_" if k == "for" else k) for k in _TOP_LEVEL_KEYS}
assert _PROFILE_FIELD_NAMES == _EXPECTED_TOP_LEVEL, (
    _PROFILE_FIELD_NAMES,
    _EXPECTED_TOP_LEVEL,
)
