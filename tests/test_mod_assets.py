"""The mod's generated assets (``plugin/hooks/generated/*.js``) are what
``scripts/export-mod-assets.py`` writes now.

The mod can't import Python, so ClaudeGlass's words, thresholds, colours,
rates and version are written out as ES modules. A change to any source
fails here until the script is run again.
"""

from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "scripts" / "export-mod-assets.py"

_spec = importlib.util.spec_from_file_location("export_mod_assets", SCRIPT)
export_mod_assets = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(export_mod_assets)

EXPECTED_FILES = {f"plugin/hooks/generated/{name}.js" for name in ("copy", "coaching", "palette", "rates", "version")}


def _exported_json(text: str) -> dict:
    """``{NAME: value}`` for each ``export const NAME = <json>;`` in a
    generated module."""
    out = {}
    for match in re.finditer(r"^export const (\w+) = (.*?);\n(?=\nexport const |\Z)", text, flags=re.M | re.S):
        out[match.group(1)] = json.loads(match.group(2))
    return out


@pytest.fixture(scope="module")
def exported() -> dict[str, str]:
    return export_mod_assets.export()


def test_the_script_makes_the_five_asset_files(exported):
    assert set(exported) == EXPECTED_FILES


def test_the_generated_files_on_disk_are_what_the_script_makes_now(exported):
    behind = export_mod_assets.stale(exported)
    assert behind == [], (
        "These generated files are out of date: "
        + ", ".join(behind)
        + ". Run `python scripts/export-mod-assets.py` and keep the result."
    )


def test_the_check_flag_names_each_file_that_is_behind(exported, tmp_path, monkeypatch, capsys):
    assert export_mod_assets.main(["--check"]) == 0
    monkeypatch.setattr(export_mod_assets, "REPO_ROOT", tmp_path)
    assert export_mod_assets.main(["--check"]) == 1
    err = capsys.readouterr().err
    for relative in EXPECTED_FILES:
        assert f"OUT OF DATE: {relative}" in err


def test_writing_puts_the_files_where_the_check_looks(exported, tmp_path, monkeypatch):
    monkeypatch.setattr(export_mod_assets, "REPO_ROOT", tmp_path)
    paths = export_mod_assets.write(exported)
    assert {p.relative_to(tmp_path).as_posix() for p in paths} == EXPECTED_FILES
    assert export_mod_assets.stale(exported) == []


def test_the_output_is_the_same_each_time(exported):
    assert export_mod_assets.export() == exported


@pytest.mark.parametrize("relative", sorted(EXPECTED_FILES))
def test_each_file_names_its_script_and_says_not_to_edit(exported, relative):
    text = exported[relative]
    assert text.startswith("// Generated by scripts/export-mod-assets.py from ")
    assert text.split("\n", 1)[0].endswith("Do not edit.")
    assert "\r" not in text and text.endswith("\n")


@pytest.mark.parametrize("relative", sorted(EXPECTED_FILES))
def test_each_export_is_json_the_engine_can_load(exported, relative):
    values = _exported_json(exported[relative])
    assert values
    assert exported[relative].count("export const ") == len(values)


def test_the_version_is_the_packages(exported):
    from claudeglass import __version__

    assert _exported_json(exported["plugin/hooks/generated/version.js"]) == {"VERSION": __version__}


def test_the_words_are_the_python_modules(exported):
    from claudeglass import mod_copy

    values = _exported_json(exported["plugin/hooks/generated/copy.js"])
    assert values == {"COPY": mod_copy.COPY, "GLOSSARY": mod_copy.GLOSSARY}


def test_the_coaching_asset_carries_the_catalogues_thresholds_tips_and_how_to(exported):
    from claudeglass import capture_catalogue

    values = _exported_json(exported["plugin/hooks/generated/coaching.js"])
    assert values["THRESHOLDS"] == capture_catalogue.COACHING_THRESHOLDS
    assert values["TIPS"] == capture_catalogue.COACHING_TIP
    assert values["HOW"] == capture_catalogue.COACHING_HOW


def test_the_rates_are_the_packaged_rate_card_in_the_settings_files_shape(exported):
    from claudeglass import mod_settings
    from claudeglass.pricing import load_pricing

    values = _exported_json(exported["plugin/hooks/generated/rates.js"])
    packaged = load_pricing(path=export_mod_assets.PACKAGE_DIR / "pricing.toml")
    assert values["RATES"] == mod_settings.pricing_block(packaged)
    assert values["RATES"]["models"]


def test_the_palette_has_both_themes_with_literal_colours(exported):
    values = _exported_json(exported["plugin/hooks/generated/palette.js"])
    assert set(values["PALETTE"]) == {"light", "dark"}
    colour = re.compile(r"#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)")
    for theme, tokens in values["PALETTE"].items():
        assert {"chart-2", "chart-4", "chart-8"} <= set(tokens), theme
        assert all(colour.fullmatch(value) for value in tokens.values()), theme
    assert values["PALETTE"]["light"] != values["PALETTE"]["dark"]


def test_the_entity_colours_follow_the_dashboards_map_and_include_the_context_parts(exported):
    values = _exported_json(exported["plugin/hooks/generated/palette.js"])
    parts = values["ENTITIES"]["part"]
    assert {"conversation", "output", "startup", "free", "other"} <= set(parts)
    for kind, keys in values["ENTITIES"].items():
        for key, themes in keys.items():
            assert set(themes) == {"light", "dark"}, f"{kind}.{key}"
    source = (export_mod_assets.STATIC_DIR / "charts.js").read_text(encoding="utf-8")
    assert "ENTITY_COLOURS" in source
    assert export_mod_assets.entity_colours() == values["ENTITIES"]
